"""마이크 decimation FIR 필터 설계 (Design the microphone decimation FIR filters).

두 경로 모두 최종 출력 8 333.33 Hz (Both paths end at 8 333.33 Hz):

1) I2S — SPH0645 (외장 / external)
    nRF54L15 PS Table 42 / 8.11.5: MCK = 32 MHz / N (정수 분주, 지터 없음),
    LRCK = MCK / RATIO, SCK = 64 × LRCK. SPH0645는 SCK 2.048–4.096 MHz 필요
    → 32 kHz(N·RATIO=1000) 불가. 선택: N=15, RATIO=64 → LRCK 33 333.33 Hz, ÷4.

2) PDM — 내장 마이크 (on-board mic, XIAO nRF54L15 Sense)
    PDM CLK = 32 MHz / PRESCALER, 출력 fs = PDM CLK / RATIO.
    선택: PRESCALER=24, RATIO=80 → CLK 1.3333 MHz, fs 16 666.67 Hz, ÷2.
    (32 MHz / (24·80) = 16 666.67 Hz = 2 × 8 333.33 Hz → I2S 경로와 같은 출력 레이트)

출력 (Outputs):
    apps/acq_fw/src/decim_coeffs.h       — I2S 경로 (DECIM_*)
    apps/acq_fw/src/decim_coeffs_pdm.h   — PDM 경로 (PDM_DECIM_*)
    figures/decim_response.png, figures/decim_response_pdm.png

실행 (Run): ``.venv/bin/python analysis/design_decim.py``
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy import signal  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CUTOFF_HZ = 3300.0  # -6 dB 지점 (새 나이퀴스트 4 166.7 Hz 아래 / below new Nyquist)
ALIAS_BAND_HZ = 2000.0  # 이 대역으로 접혀 들어오는 성분을 평가 (alias check band)


@dataclass(frozen=True)
class FilterSpec:
    """Decimation 필터 하나의 사양 (One decimation filter spec)."""

    name: str          # 그림 제목·로그용 (label)
    fs_in: float       # 입력 샘플링 레이트 [Hz]
    decim: int         # decimation 비율
    num_taps: int
    kaiser_beta: float
    prefix: str        # C 매크로·배열 접두어 (C identifier prefix)
    header: str        # apps/acq_fw/src/ 아래 파일명
    figure: str        # figures/ 아래 파일명

    @property
    def fs_out(self) -> float:
        return self.fs_in / self.decim


SPECS = [
    FilterSpec("I2S SPH0645", 32e6 / (15 * 64), 4, 63, 7.0,
               "DECIM", "decim_coeffs.h", "decim_response.png"),
    FilterSpec("PDM on-board", 32e6 / (24 * 80), 2, 31, 7.0,
               "PDM_DECIM", "decim_coeffs_pdm.h", "decim_response_pdm.png"),
]


def design(spec: FilterSpec) -> np.ndarray:
    """firwin으로 저역통과 FIR 계수를 만든다 (Design low-pass FIR taps)."""
    return signal.firwin(spec.num_taps, CUTOFF_HZ, fs=spec.fs_in,
                         window=("kaiser", spec.kaiser_beta))


def response_db(spec: FilterSpec, taps: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    f, h = signal.freqz(taps, worN=1 << 14, fs=spec.fs_in)
    return f, 20 * np.log10(np.maximum(np.abs(h), 1e-12))


def report(spec: FilterSpec, taps: np.ndarray) -> dict[str, float]:
    """주요 지점의 감쇠량 [dB] (Attenuation at key frequencies)."""
    f, mag = response_db(spec, taps)

    def at(freq: float) -> float:
        return float(np.interp(freq, f, mag))

    # 0–2 kHz 대역으로 접혀 들어오는 성분 (aliases into 0–2 kHz):
    # 출력 fs의 배수 k·fs_out 주변 ±2 kHz 전부 (all bands k·fs_out ± 2 kHz, k ≥ 1)
    alias = np.zeros_like(f, dtype=bool)
    for k in range(1, spec.decim + 1):
        alias |= np.abs(f - k * spec.fs_out) <= ALIAS_BAND_HZ
    return {
        "gain_1k": at(1000), "gain_2k": at(2000), "gain_3k": at(3000),
        "gain_nyq_out": at(spec.fs_out / 2),
        "worst_alias_into_0_2k": float(mag[alias].max()),
    }


def write_header(spec: FilterSpec, taps: np.ndarray, path: Path) -> None:
    p = spec.prefix
    guard = path.name.upper().replace(".", "_") + "_"
    lines = [
        "/*",
        " * 자동 생성 — 직접 고치지 말 것 (Auto-generated by analysis/design_decim.py)",
        f" * {spec.name}: FS_IN = {spec.fs_in:.4f} Hz, DECIM = {spec.decim}, "
        f"FS_OUT = {spec.fs_out:.4f} Hz",
        f" * {spec.num_taps} taps, cutoff {CUTOFF_HZ:.0f} Hz, Kaiser beta {spec.kaiser_beta}",
        " */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"#define {p}_FACTOR   {spec.decim}",
        f"#define {p}_NUM_TAPS {spec.num_taps}",
        "",
        "/* CMSIS-DSP는 계수를 시간 역순으로 받지만 대칭 FIR이라 순서 무관",
        " * CMSIS-DSP expects time-reversed taps; a symmetric FIR is unaffected */",
        f"static const float {p.lower()}_coeffs[{p}_NUM_TAPS] = {{",
    ]
    for i in range(0, len(taps), 4):
        chunk = ", ".join(f"{v: .9e}f" for v in taps[i:i + 4])
        lines.append(f"\t{chunk},")
    lines += ["};", "", f"#endif /* {guard} */", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def plot(spec: FilterSpec, taps: np.ndarray, path: Path) -> None:
    f, mag = response_db(spec, taps)
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(f / 1000, mag, lw=1.2)
    ax.axvline(spec.fs_out / 2 / 1000, color="tab:red", ls="--", lw=1,
               label=f"new Nyquist {spec.fs_out / 2:.0f} Hz")
    ax.axvline(CUTOFF_HZ / 1000, color="tab:gray", ls=":", lw=1,
               label=f"cutoff {CUTOFF_HZ:.0f} Hz")
    ax.set(xlabel="Frequency [kHz]", ylabel="Gain [dB]", ylim=(-110, 5),
           xlim=(0, spec.fs_in / 2000),
           title=f"{spec.name} decimation FIR: {spec.num_taps} taps, "
                 f"{spec.fs_in:.0f} Hz ÷ {spec.decim} → {spec.fs_out:.0f} Hz")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main() -> None:
    for spec in SPECS:
        taps = design(spec)
        hdr = ROOT / "apps" / "acq_fw" / "src" / spec.header
        hdr.parent.mkdir(parents=True, exist_ok=True)
        write_header(spec, taps, hdr)
        plot(spec, taps, ROOT / "figures" / spec.figure)
        print(f"--- {spec.name} ({spec.fs_in:.2f} Hz ÷ {spec.decim}) ---")
        for k, v in report(spec, taps).items():
            print(f"{k:24s} {v:8.2f} dB")
        print(f"DC gain sum(taps) = {taps.sum():.6f}")
        print(f"wrote {hdr}")


if __name__ == "__main__":
    main()
